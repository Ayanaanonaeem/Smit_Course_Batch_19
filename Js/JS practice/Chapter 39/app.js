//  Switch and case statement

var value = "ayan";
switch (value) {
case "jawaid":
	console.log("this is jawaid");
break;

case "ayan":
	console.log("here is ayan");
break;

default:
	console.log("No one is Ayan");
break;
}


var fruit="peach"

